def _edit_csv(p, row_match, col, value):
    lines = p.read_text().splitlines()
    h = lines[0].split(",")
    i = h.index(col)
    for k, ln in enumerate(lines[1:], 1):
        if row_match(ln):
            parts = ln.split(",")
            parts[i] = value
            lines[k] = ",".join(parts)
            break
    p.write_text("\n".join(lines) + "\n")



def _ulp_up(text):
    import math
    return repr(math.nextafter(float(text), math.inf))


def test_twin_prices_from_quotes_are_exact_and_computed_prices_relative(root, world_copy):
    """Amendment B2 item 5 (R-J5-1 .. R-J5-3): a twin's P_e (a mid of exact quotes) and a time-exit P_x are compared
    exactly, so one ulp is a finding; a P_x at X (a gap exit) is a computed price, compared at rel <= 1e-9."""
    tw = world_copy / "reports/system/lab_v2/twins.csv"
    _edit_csv(tw, lambda ln: ln.startswith("S2,2026-11-09,12:10"), "P_e", _ulp_up("4118.059"))
    _edit_csv(tw, lambda ln: ln.startswith("S3,2026-11-17,14:30"), "P_x", _ulp_up("4128.8574918337645"))
    ctx = recompute.Ctx(root, world_copy, NOW, PINS)
    out = []
    recompute.check_v2_lab(ctx, out, cover_days={"2026-11-09", "2026-11-17"})
    assert [(f.subject, f.detail.split()[0]) for f in out] == [("v2 twins S2 2026-11-09", "P_e")], out
    assert "(prices exact)" in out[0].detail


def test_v2_settlement_follows_the_forecast_coverage_gate(root, world_copy):
    """R-V2-27 (lab review MF1): a day is settled only when v1's store, as the settling run read it (computed_utc <=
    settled_utc), holds its 23 rows; no weekday is skipped; F_S comes from the rows the run read."""
    (world_copy / "data").unlink()
    shutil.copytree(root / "tests/judge_fixtures/synthetic_world/data", world_copy / "data")
    fc = world_copy / "data/system/forecasts.csv"
    # one slot of 2026-11-12 (settled 2026-11-14T03:20Z) written only by the run of 2026-11-21
    _edit_csv(fc, lambda ln: ln.startswith("2026-11-12,7,"), "computed_utc", "2026-11-21T03:20:00Z")
    ctx = recompute.Ctx(root, world_copy, NOW, PINS)
    out = []
    recompute.check_v2_lab(ctx, out, cover_days=set())
    assert [f.subject for f in out] == ["v2 lab_days 2026-11-12"] and "23 rows" in out[0].detail, out
    # a skipped weekday: 2026-11-18 removed from lab_days.csv (and its rows), 11-19 still settled
    ld = world_copy / "reports/system/lab_v2/lab_days.csv"
    ld.write_text("".join(x for x in ld.read_text().splitlines(True) if not x.startswith("2026-11-18,")))
    for name in ("audit", "decisions", "trades", "twins", "eproc"):
        p = world_copy / f"reports/system/lab_v2/{name}.csv"
        p.write_text("".join(x for x in p.read_text().splitlines(True) if ",2026-11-18," not in x))
    out = []
    recompute._check_v2_settlement(recompute.Ctx(root, world_copy, NOW, PINS), out,
                                   recompute._ledger(world_copy, "reports/system/lab_v2/lab_days.csv"),
                                   recompute.forecasts.store_rows(world_copy))
    assert any(f.subject == "v2 lab_days 2026-11-19" and "2026-11-18 was not settled" in f.detail for f in out), out


def test_store_covers_and_a_passed_over_day():
    keys = {("2026-11-12", s) for s in range(23)} | {("2026-11-16", 0)}
    assert recompute.store_covers(keys, "2026-11-12")
    assert not recompute.store_covers(keys - {("2026-11-12", 22)}, "2026-11-12")
    assert recompute.store_covers(keys, "2026-11-13")          # no row of the day, a later day stored: passed over
    assert not recompute.store_covers(keys, "2026-11-17")      # nothing later: not yet written
